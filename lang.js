  let currentLang = 'nl';
  
  /* ── Alle elementen updaten ────────────────────────────────── */
  function applyTranslations(lang) {
    const t = translations[lang];
    document.documentElement.lang = lang;
  
    // Helper: zet innerHTML van element met data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (t[key] !== undefined) el.innerHTML = t[key];
    });
  
    // Helper: zet placeholder van inputs met data-i18n-ph
    document.querySelectorAll('[data-i18n-ph]').forEach(el => {
      const key = el.getAttribute('data-i18n-ph');
      if (t[key] !== undefined) el.placeholder = t[key];
    });
  
    // Toggle knop updaten
    const btn = document.getElementById('langToggle');
    if (btn) {
      btn.textContent = lang === 'nl' ? 'EN' : 'NL';
      btn.setAttribute('aria-label', lang === 'nl' ? 'Switch to English' : 'Schakel naar Nederlands');
    }
  }
  
  /* ── Toggle functie ────────────────────────────────────────── */
  function toggleLang() {
    currentLang = currentLang === 'nl' ? 'en' : 'nl';
    applyTranslations(currentLang);
  }
  
  /* ── Init op pagina load ───────────────────────────────────── */
  document.addEventListener('DOMContentLoaded', () => applyTranslations('nl'));
  